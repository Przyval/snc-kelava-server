"""
Notification Center API
========================
In-app notifications for operational alerts:
- Contract expiring soon
- New complaints
- Missed visits (SLA breach)
- Low completion rate warnings
- System health alerts

Auto-generated by rules, consumed by dashboard.
"""

from datetime import datetime

from flask import Blueprint, g, jsonify, request
from core.security import require_auth, require_role

from kil.db.kelava_db import execute_kelava_query, execute_kelava_query_single

notif_bp = Blueprint("notifications", __name__, url_prefix="/notifications")

_TABLE_ENSURED = False


def _fmt(row):
    if not row:
        return {}
    item = dict(row)
    for k, v in item.items():
        if hasattr(v, "isoformat"):
            item[k] = v.isoformat()
    return item


# ── Get Notifications ──────────────────────────────────────


@notif_bp.route("", methods=["GET"])
@require_auth
def list_notifications():
    """
    Get notifications for current user.
    Query params: unread_only (bool), category, page, per_page
    """
    _ensure_tables()
    user = getattr(g, "current_user", None)
    user_id = user.id if user else None
    role = user.role if user else None

    unread_only = request.args.get("unread_only", "").lower() in ("1", "true")
    category = request.args.get("category")
    page = int(request.args.get("page", 1))
    per_page = min(int(request.args.get("per_page", 20)), 100)
    offset = (page - 1) * per_page

    where = "(n.target_user_id = %s OR n.target_role = %s OR n.target_role = 'all')"
    params = [user_id, role]

    if unread_only:
        where += " AND n.read_at IS NULL"
    if category:
        where += " AND n.category = %s"
        params.append(category)

    params.extend([per_page, offset])

    rows = execute_kelava_query(
        f"""
        SELECT n.*
        FROM enterprise_notifications n
        WHERE {where}
        ORDER BY n.created_at DESC
        LIMIT %s OFFSET %s
        """,
        tuple(params),
    )

    unread_count = execute_kelava_query_single(
        f"""
        SELECT COUNT(*) AS cnt
        FROM enterprise_notifications n
        WHERE (n.target_user_id = %s OR n.target_role = %s OR n.target_role = 'all')
          AND n.read_at IS NULL
        """,
        (user_id, role),
    )

    return jsonify({
        "notifications": [_fmt(r) for r in rows],
        "unread_count": unread_count["cnt"] if unread_count else 0,
        "page": page,
    })


